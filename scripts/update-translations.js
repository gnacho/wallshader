import { PAPER_SHADERS } from '../src/paper-catalog.js';
import { languages, run } from './build-translations.js';
import { spawnSync } from 'node:child_process';

// Keep Paper's generated catalog byte-for-byte upstream-compatible. This
// extraction-only companion is reproducible from the committed metadata.
const messages = new Set(['none', 'contain', 'cover']);
for (const shader of Object.values(PAPER_SHADERS)) {
  messages.add(shader.name);
  messages.add(shader.category);
  for (const preset of shader.presets) messages.add(preset.name);
  for (const field of shader.fields) {
    messages.add(field.label);
    if (field.description) messages.add(field.description);
    for (const option of field.options ?? []) messages.add(option);
  }
}
const output = [
  '// Generated by scripts/update-translations.js. Do not edit by hand.',
  "import { N_ } from '../src/translation.js';",
  '',
  '// Translators: Paper shader names, controls, descriptions, and enum labels.',
  ...[...messages].sort().map((message) => `N_(${JSON.stringify(message)});`),
  '',
].join('\n');
const catalogFile = new URL('../po/paper-catalog.js', import.meta.url);
if (Bun.argv.includes('--check')) {
  if ((await Bun.file(catalogFile).text()) !== output)
    throw new Error(
      'Run bun run translations:update to refresh Paper messages.',
    );
  process.exit(0);
}
await Bun.write(catalogFile, output);
run('xgettext', [
  ...(spawnSync('xgettext', ['--help'], { encoding: 'utf8' }).stdout?.includes(
    '--no-git',
  )
    ? ['--no-git']
    : []),
  '--from-code=UTF-8',
  '--add-comments=Translators:',
  '--keyword=_',
  '--keyword=N_',
  '--keyword=ngettext:1,2',
  '--keyword=pgettext:1c,2',
  '--package-name=Wallshader',
  '--copyright-holder=Wallshader contributors',
  '--msgid-bugs-address=https://github.com/stonega/wallshader/issues',
  '--files-from=po/POTFILES',
  '--output=po/wallshader.pot',
]);
for (const language of await languages())
  run('msgmerge', [
    '--update',
    '--backup=none',
    `po/${language}.po`,
    'po/wallshader.pot',
  ]);
